// Helper to resolve product image URL
export function resolveProductImage(product) {
  if (product.image) return product.image;
  if (product.relImage) {
    const assetKey = `../assets/IoT Robotics Drone & Embedded Systems Categories and Components/${product.relImage}`;
    if (assetImages[assetKey]) {
      return assetImages[assetKey];
    }
  }
  if (product.thumbnail) {
    if (product.thumbnail.startsWith('http') || product.thumbnail.startsWith('data:')) {
      return product.thumbnail;
    }
    return `http://localhost:5000/uploads/${product.thumbnail}`;
  }
  return '';
}
